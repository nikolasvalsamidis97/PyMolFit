def test_ozone_layer_columns_filters_and_transmission():
    atmosphere = _atmosphere()
    wave = np.linspace(0.4, 0.7, 501)
    continuum = LBLRTMO3Continuum.from_package_data()
    expected = sum(
        continuum.optical_depth_layer(
            1e4 / wave,
            temperature_k=layer.temperature_k,
            o3_column_cm2=layer.column_density_cm2("O3"),
        )
        for layer in atmosphere.layers
    )
    names, basis = O3ContinuumAbsorption().optical_depth_basis(wave, atmosphere)
    assert names == ("O3",)
    np.testing.assert_allclose(basis[0], expected)
    names, basis = combine_optical_depth_components(
        wave,
        atmosphere,
        (O3ContinuumAbsorption(),),
        species=("H2O",),
    )
    assert names == ()
    assert basis.shape == (0, wave.size)
    config = PhysicalModelConfig(o3_continuum=True, species_scales={"O3": 1.5})
    transmission = physical_transmission_model(wave, LineList.empty_hitran(), atmosphere, config)
    np.testing.assert_allclose(transmission, np.exp(-1.5 * expected))
    disabled = physical_transmission_model(
        wave,
        LineList.empty_hitran(),
        atmosphere,
        replace(config, o3_continuum=False),
    )
    np.testing.assert_array_equal(disabled, 1)


def test_ozone_without_profile_abundance_adds_no_opacity():
    atmosphere = AtmosphereProfile.single_layer(mixing_ratios={"O2": 0.21})
    names, basis = physical_optical_depth_basis(
        np.array([0.55, 0.6]),
        LineList.empty_hitran(),
        atmosphere,
        PhysicalModelConfig(o3_continuum=True),
    )
    assert "O3" not in names
    assert basis.shape == (0, 2)


def test_oxygen_uv_is_included_by_existing_continuum_option():
    grid = np.array([40000.0, 48000.0, 60000.0, 80000.0])
    continuum = LBLRTMO2Continuum.from_package_data()
    tau = continuum.optical_depth_layer(
        grid,
        o2_column_cm2=1e23,
        air_column_cm2=5e23,
        air_amagat=0.5,
        pressure_mbar=500.0,
        temperature_k=250,
        n2_vmr=0.79,
        o2_vmr=0.21,
        h2o_vmr=0,
    )
    expected = 1e23 * _o2_uv_cross_section(grid, pressure_mbar=500.0, temperature_k=250, jrad=1)
    np.testing.assert_allclose(tau, expected)
    assert np.all(tau > 0)
    assert np.all(
        _o2_uv_cross_section(
            np.array([1000.0, 20000.0, 35000.0, 100001.0]),
            pressure_mbar=500,
            temperature_k=250,
            jrad=1,
        )
        == 0
    )


@pytest.mark.parametrize("interface", ["arrays", "file"])
def test_ozone_correction_recovers_column_and_corrected_flux(interface, tmp_path):
    wave = np.linspace(0.45, 0.7, 600)
    atmosphere = _atmosphere()
    transmission = physical_transmission_model(
        wave,
        LineList.empty_hitran(),
        atmosphere,
        PhysicalModelConfig(o3_continuum=True, species_scales={"O3": 1.6}),
    )
    flux = 2.5 * transmission
    options = {
        "atmosphere": atmosphere,
        "o3_continuum": True,
        "o3_continuum_xo3cn": 0.8,
        "aer_catalog": None,
        "auto_segment": False,
        "automatic_fit_regions": False,
        "continuum_order": 0,
        "loss": "linear",
        "fit_wavelength_shift": False,
        "lsf_sigma_pixels": 0.0,
        "fit_lsf_sigma": False,
        "lsf_lorentz_fwhm_pixels": 0.0,
        "fit_lsf_lorentz_fwhm": False,
        "lsf_variable_width": False,
        "estimate_uncertainties": True,
    }
    error = np.full(wave.size, 0.001)
    if interface == "arrays":
        result = correct_arrays(wave, flux, uncertainty=error, **options)
    else:
        path = tmp_path / "spectrum.txt"
        np.savetxt(path, np.column_stack([wave, flux, error]))
        result = correct_file(path, wavelength_medium="vacuum", uncertainty_col=2, **options)
    assert result.success
    assert result.species_scales["O3"] == pytest.approx(2.0, rel=1e-5)
    np.testing.assert_allclose(result.transmission, transmission, rtol=1e-6)
    np.testing.assert_allclose(result.corrected.flux, 2.5, rtol=1e-6)
    assert result.transmission_uncertainty is not None
    assert np.all(np.isfinite(result.corrected.uncertainty))


