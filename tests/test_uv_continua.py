def _atmosphere():
    return AtmosphereProfile(
        layers=(
            AtmosphereLayer(0.2, 230.0, 3000.0, {"O3": 4e-6, "O2": 0.21}),
            AtmosphereLayer(0.05, 250.0, 5000.0, {"O3": 6e-6, "O2": 0.21}),
        )
    )


def test_matches_independent_fortran_reference():
    # Generated by tools/validate_lblrtm_uv_continua.py using the original
    # Fortran routines, not the Python implementation or extracted npz tables.
    with np.load(Path(__file__).parent / "data" / "lblrtm_uv_reference.npz") as data:
        cases = data["cases"]
    ozone = LBLRTMO3Continuum.from_package_data()
    for branch, temperature, pressure, jrad, wavenumber, reference in cases:
        grid = np.array([wavenumber])
        if branch <= 3:
            actual = ozone.optical_depth_layer(
                grid,
                o3_column_cm2=1e18,
                temperature_k=temperature,
                jrad=int(jrad),
            )
        else:
            actual = 1e23 * _o2_uv_cross_section(
                grid,
                pressure_mbar=pressure,
                temperature_k=temperature,
                jrad=int(jrad),
            )
        np.testing.assert_allclose(actual[0], reference, rtol=2e-9, atol=1e-15)


@pytest.mark.parametrize("temperature", [195.0, 230.0, 273.15, 296.0])
def test_ozone_support_scaling_and_nonnegative_absorption(temperature):
    ozone = LBLRTMO3Continuum.from_package_data()
    grid = np.linspace(8000, 60000, 52001)
    tau = ozone.optical_depth_layer(grid, temperature_k=temperature, o3_column_cm2=1e18)
    assert np.all(np.isfinite(tau))
    assert np.all(tau >= 0)
    outside = (grid < 8920) | ((grid > 24665) & (grid < 27370)) | (grid > 54000)
    assert np.all(tau[outside] == 0)
    assert tau[np.argmin(abs(grid - 17000))] > 0
    assert tau[np.argmin(abs(grid - 35000))] > 0
    assert tau[np.argmin(abs(grid - 45000))] > 0
    np.testing.assert_allclose(
        ozone.optical_depth_layer(grid, temperature_k=temperature, o3_column_cm2=2e18, xo3cn=0.7),
        1.4 * tau,
    )
    np.testing.assert_array_equal(
        ozone.optical_depth_layer(grid, temperature_k=temperature, o3_column_cm2=0),
        0,
    )


def test_ozone_join_is_not_double_counted_and_independent_of_grid_span():
    ozone = LBLRTMO3Continuum.from_package_data()
    grid = np.array([40799.0, 40800.0, 40801.0, 45000.0, 54000.0])
    tau = ozone.optical_depth_layer(grid, temperature_k=250, o3_column_cm2=1e18)
    assert tau[1] == pytest.approx(9.91204, rel=1e-12)
    for i, value in enumerate(grid):
        separate = ozone.optical_depth_layer(
            np.array([value]), temperature_k=250, o3_column_cm2=1e18
        )
        assert separate[0] == tau[i]
    np.testing.assert_allclose(
        ozone.optical_depth_layer(grid[::-1], temperature_k=250, o3_column_cm2=1e18),
        tau[::-1],
    )


