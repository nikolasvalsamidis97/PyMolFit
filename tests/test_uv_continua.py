def test_cli_forwards_ozone_to_physical_correction(monkeypatch):
    captured = {}

    def fake_correct(*args, **kwargs):
        captured.update(kwargs)

    monkeypatch.setattr("pymolfit.cli.correct_file", fake_correct)
    assert (
        main(
            [
                "fit",
                "input.txt",
                "output.txt",
                "--o3-continuum",
                "--no-auto-aer",
                "--o3-continuum-xo3cn",
                "0.7",
            ]
        )
        == 0
    )
    assert captured["o3_continuum"] is True
    assert captured["o3_continuum_xo3cn"] == 0.7
    assert captured["physical"] is True
